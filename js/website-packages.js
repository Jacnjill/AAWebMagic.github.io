/* Public CMS packages. Render only the fields this site publishes. */
(function () {
  const section = document.querySelector('[data-cms-packages]');
  if (!section) return;

  const status = section.querySelector('[data-cms-status]');
  const list = section.querySelector('[data-cms-list]');
  const destination = section.dataset.cmsDestination;
  const slug = section.hasAttribute('data-cms-detail')
    ? new URLSearchParams(location.search).get('id') : null;
  const boardLabels = new Map([
    ['room_only', 'Room only'],
    ['self_catering', 'Self-catering'],
    ['bed_and_breakfast', 'Bed and breakfast'],
    ['half_board', 'Half board'],
    ['full_board', 'Full board'],
    ['all_inclusive', 'All-inclusive']
  ]);
  const excluded = /\b(?:ATOL|ABTA|Trustpilot|offers?|protected|testimonials?|\d[ -]stars?)\b|[★☆$€]|\d\s*%/i;

  function publicText(value) {
    return typeof value === 'string' && !excluded.test(value) ? value.trim() : '';
  }

  function appendText(parent, tag, text) {
    if (!text) return;
    const element = document.createElement(tag);
    element.textContent = text;
    parent.append(element);
  }

  function cardFor(pkg, title) {
    const card = document.createElement('article');
    card.className = 'card';
    appendText(card, 'h3', title);
    const nights = Number.isInteger(pkg.nights) && pkg.nights > 0
      ? pkg.nights + (pkg.nights === 1 ? ' night' : ' nights') : '';
    const details = [nights, boardLabels.get(pkg.board), publicText(pkg.departureAirport)];
    appendText(card, 'p', details.filter(Boolean).join(' · '));

    const price = pkg.price;
    const display = price?.live === true && details.every(Boolean)
      && /^from £[\d,]+(?:\.\d{2})? pp$/i.test(price.display) ? price.display : '';
    appendText(card, 'p', display || "Ask for today's price on WhatsApp");
    if (display && /^\d{4}-\d{2}-\d{2}$/.test(price.quoteDate)) {
      appendText(card, 'p', 'Price checked ' + price.quoteDate.split('-').reverse().join('/'));
    }

    const link = document.createElement('a');
    link.className = 'btn btn-wa';
    link.dataset.wa = '';
    link.dataset.location = 'cms-package';
    link.dataset.waInterest = title;
    link.textContent = 'Ask about this package';
    card.append(link);
    return card;
  }

  fetch(TNT.websiteContentEndpoint, {
    credentials: 'omit',
    signal: AbortSignal.timeout?.(8000)
  })
    .then(response => response.ok ? response.json() : null)
    .then(feed => {
      if (feed?.enabled !== true || !Array.isArray(feed.packages)) return;
      const cards = document.createDocumentFragment();
      for (const pkg of feed.packages) {
        const title = publicText(pkg?.title);
        if (!title || (destination && pkg.destinationSlug !== destination)
          || (slug && pkg.slug !== slug)) continue;
        cards.append(cardFor(pkg, title));
      }
      if (!cards.childElementCount) return;

      const count = cards.childElementCount;
      TNTSite.refresh(cards);
      list.replaceChildren(cards);
      status.textContent = count === 1 ? '1 package available' : count + ' packages available';
    })
    .catch(() => {
      // The enquiry message and WhatsApp link remain available.
    });
})();

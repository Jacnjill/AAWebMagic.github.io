/* Public CMS packages and the shared holiday ideas shown when no package matches. */
(function () {
  const section = document.querySelector('[data-cms-packages]');
  if (!section) return;

  const heading = document.getElementById(section.getAttribute('aria-labelledby'));
  const status = section.querySelector('[data-cms-status]');
  const list = section.querySelector('[data-cms-list]');
  const { cmsDestination: destination, cmsTopic: topic } = section.dataset;
  const slug = section.hasAttribute('data-cms-detail')
    ? new URLSearchParams(location.search).get('id') : null;
  const ideas = [
    { destination: 'turkey', topic: 'family', title: 'Family all-inclusive holidays in Turkey',
      description: 'Tell us what your family looks for in a holiday.' },
    { destination: 'greece', topic: 'couples', title: 'Couples’ breaks in Greece',
      description: 'Tell us which islands or mainland destinations interest you.' },
    { destination: 'turkey', topic: 'villa', title: 'Villa holidays in Turkey',
      description: 'Tell us where in Turkey you’d like to stay.' },
    { destination: 'turkey', topic: 'spa', title: 'Beach and spa breaks in Turkey',
      description: 'Tell us which part of the coast you’d like to explore.' },
    { destination: 'spain', topic: 'adventure', title: 'Walking holidays in Spain',
      description: 'Tell us what kind of walks you enjoy.' },
    { destination: 'turkey', topic: 'heritage', title: 'Muslim-friendly heritage breaks in Turkey',
      description: 'Tell us which places you’d like to visit.' }
  ];
  const excluded = /\b(?:ATOL|ABTA|Trustpilot|offers?|protected|testimonials?|luxury|ultimate|best|cheapest|guaranteed|nights?|includes?|\d[ -]*stars?)\b|[★☆£$€]|\d\s*%|\b\d{1,4}[./-]\d{1,2}[./-]\d{1,4}\b/i;

  function cardFor(title, phrase, description) {
    const card = document.createElement('article');
    card.className = 'card';
    const name = document.createElement('h3');
    name.textContent = title;
    card.append(name);
    if (description) {
      const copy = document.createElement('p');
      copy.textContent = description;
      card.append(copy);
    }

    const link = document.createElement('a');
    link.className = 'btn btn-wa';
    link.dataset.wa = '';
    link.dataset.location = phrase ? 'cms-package' : 'cms-packages';
    if (phrase) link.dataset.waText = phrase;
    link.textContent = 'Ask us for prices on WhatsApp';
    card.append(link);
    return card;
  }

  function showCards(cards, title) {
    TNTSite.refresh(cards);
    list.replaceChildren(cards);
    heading.textContent = title;
    status.textContent = title + ' updated';
    status.classList.add('sr-only');
    section.querySelector('[data-cms-enquiry]').hidden = true;
  }

  function showIdeas() {
    const cards = document.createDocumentFragment();
    for (const idea of ideas) {
      if (destination && idea.destination !== destination) continue;
      if (topic && idea.topic !== topic) continue;
      const phrase = TNTLogic.sourcePhrase('I-' + idea.destination + '-' + idea.topic);
      cards.append(cardFor(idea.title, phrase, idea.description));
    }
    if (cards.childElementCount) showCards(cards, 'Holiday ideas');
  }

  fetch(TNT.websiteContentEndpoint, {
    credentials: 'omit',
    signal: AbortSignal.timeout?.(8000)
  })
    .then(response => response.ok ? response.json() : null)
    .catch(() => null)
    .then(feed => {
      const cards = document.createDocumentFragment();
      if (feed?.enabled === true && Array.isArray(feed.packages)) {
        const destinations = new Map((Array.isArray(feed.destinations) ? feed.destinations : [])
          .filter(row => row && typeof row.slug === 'string')
          .map(row => [row.slug, row.name]));
        const phraseCounts = new Map();
        // Count against the entire feed so page filters cannot hide collisions.
        const packages = feed.packages.filter(pkg => typeof pkg?.title === 'string' && pkg.title.trim())
          .map(pkg => {
            const title = pkg.title.trim();
            const phrase = TNTLogic.packagePhrase(title, destinations.get(pkg.destinationSlug));
            const key = TNTLogic.phraseKey(phrase);
            if (key) phraseCounts.set(key, (phraseCounts.get(key) || 0) + 1);
            return { pkg, title, phrase, key };
          });
        for (const { pkg, title, phrase, key } of packages) {
          if (excluded.test(title) || (destination && pkg.destinationSlug !== destination)
            || (slug && pkg.slug !== slug)) continue;
          cards.append(cardFor(title, phraseCounts.get(key) === 1 ? phrase : ''));
        }
      }
      if (cards.childElementCount) showCards(cards, 'Holiday packages');
      else showIdeas();
    });
})();
